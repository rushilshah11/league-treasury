// Copies the LeagueTreasury ABI from Foundry's build output into the frontend.
// Run after `forge build` (or `make abi`). Writes:
//   src/abi/leagueTreasuryAbi.ts    typed constant for the app (wagmi/viem infer types from `as const`)
//   src/abi/leagueTreasuryAbi.json  plain JSON for Node scripts like the standings bot
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const artifactPath = resolve(here, '../../out/LeagueTreasury.sol/LeagueTreasury.json')
const outDir = resolve(here, '../src/abi')

const { abi } = JSON.parse(readFileSync(artifactPath, 'utf8'))

mkdirSync(outDir, { recursive: true })
writeFileSync(
  resolve(outDir, 'leagueTreasuryAbi.ts'),
  `// Generated by scripts/sync-abi.mjs from Foundry's out/ folder. Do not edit by hand.\n` +
    `// \`as const\` lets wagmi and viem infer function names, arguments and return types.\n` +
    `export const leagueTreasuryAbi = ${JSON.stringify(abi, null, 2)} as const\n`,
)
writeFileSync(resolve(outDir, 'leagueTreasuryAbi.json'), JSON.stringify(abi, null, 2) + '\n')
console.log(`Wrote ${abi.length} ABI entries to ${outDir}`)
